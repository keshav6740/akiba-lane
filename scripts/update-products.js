
const fs = require('fs');
const path = require('path');

const imageDirs = [
  { dir: 'public/images/individual', category: 'individual' },
  { dir: 'public/images/set', category: 'set' },
  { dir: 'public/images/hp', category: 'hp' },
];

const outputFilePath = 'src/lib/products.ts';

let allProducts = [];
let idCounter = 1;

imageDirs.forEach(({ dir, category }) => {
  const files = fs.readdirSync(dir);
  files.forEach(file => {
    const extension = path.extname(file);
    const basename = path.basename(file, extension);

    // Regex to capture name and price. Assumes price is at the end.
    // It will match the last sequence of digits as the price, optionally followed by "Each".
    const match = basename.match(/^(.*?)\s*(\d+)(?:Each)?$/i);

    if (match) {
      let name = match[1].trim();
      const price = parseInt(match[2], 10);
      const id = `${category.slice(0, 3)}-${idCounter++}`;

      // A simple rarity logic based on price
      let rarity = 'C';
      if (price > 3000) {
        rarity = 'UR';
      } else if (price > 2000) {
        rarity = 'SSR';
      } else if (price > 800) {
        rarity = 'SR';
      } else if (price > 400) {
        rarity = 'R';
      }


      allProducts.push({
        id,
        name,
        price,
        currency: 'Rs.',
        category,
        image: `/images/${category}/${file}`,
        rarity,
      });
    }
  });
});

const fileContent = `import { Product } from './data';

// This file is auto-generated by scripts/update-products.js
// Do not edit this file directly.

export const rawProducts: Product[] = ${JSON.stringify(allProducts, null, 2)};

export { rawProducts as products };
`;

fs.writeFileSync(outputFilePath, fileContent);

console.log(`Successfully generated ${outputFilePath} with ${allProducts.length} products.`);
